#!/usr/bin/env python3
"""Generate the UI framework migration baseline.

Lines are `rule|repo-path|count`. UiFrameworkTest only fails when a file exceeds its
recorded count, so fixing a file shrinks the baseline on the next run and new files
start at zero.
"""
from __future__ import annotations
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/test/resources/ui-framework-baseline.txt"

RULES = [
    ("removed-page-template", re.compile(r"\b(LunoScreen|LunoScreenLazy|LunoScreenPlain|HomeShell)\b"), lambda p: True),
    ("scaffold-outside-design", re.compile(r"\bScaffold\s*\("), lambda p: not p.startswith("ui/design/src/main/java/")),
    ("raw-dp", re.compile(r"\b\d+(?:\.\d+)?\.dp\b"), None),
    ("raw-font-size", re.compile(r"\bfontSize\s*=\s*\d"), None),
    ("manual-segmented-shape", re.compile(r"\bsegmentedShape\s*\("), None),
    ("direct-lazy-column", re.compile(r"\bLazyColumn\s*\("), None),
    ("direct-material-card", re.compile(r"\bCard\s*\("), None),
]


def is_strict(path: str) -> bool:
    return (
        path.startswith("app/src/main/java/hunoia/luno/ui/home/")
        or path.startswith("app/src/main/java/hunoia/luno/ui/settings/")
        or (path.startswith("feature/") and "/settings/" in path)
    )


def is_page_or_settings(path: str) -> bool:
    return path.startswith("app/src/main/java/hunoia/luno/ui/") or (
        path.startswith("feature/") and ("/settings/" in path or "/ui/" in path)
    )


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*[\s\S]*?\*/", "", text)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def main() -> None:
    paths = [
        *ROOT.glob("app/src/main/**/*.kt"),
        *ROOT.glob("feature/*/src/main/**/*.kt"),
        *ROOT.glob("ui/design/src/main/**/*.kt"),
    ]
    lines = ["# AUTO-GENERATED by scripts/ui_baseline.py; 规则|仓库相对路径|计数"]
    for path in sorted(set(paths)):
        rel = path.relative_to(ROOT).as_posix()
        code = strip_comments(path.read_text(encoding="utf-8"))
        for rule, pattern, include in RULES:
            if include is not None and not include(rel):
                continue
            if rule == "raw-dp" and not (is_strict(rel) and not rel.endswith("ui/theme/Dimension.kt") and not rel.endswith("ui/theme/DockDimension.kt")):
                continue
            if rule == "raw-font-size" and not (is_strict(rel) and "/ui/theme/" not in rel):
                continue
            if rule in {"manual-segmented-shape", "direct-lazy-column", "direct-material-card"} and not is_page_or_settings(rel):
                continue
            count = len(pattern.findall(code))
            if count:
                lines.append(f"{rule}|{rel}|{count}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines) - 1} entries)")


if __name__ == "__main__":
    main()